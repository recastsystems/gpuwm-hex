"""The processor-proof dispatcher (nt_host.inc) for every kernel in nt_kernels.json:
binds a launch bundle's slots to the forward kernel, its tangent entry and its taped reverse, in the forward's own
argument order. usage: gen_host.py nt_kernels.json OUT/nt_host.inc"""
import json, sys
K = json.load(open(sys.argv[1]))['kernels']
o = ['// GENERATED by gen_host.py. Do not edit.']
tab = []
for name, k in K.items():
    A = k['args']
    scal = [(i, a) for i, a in enumerate(A) if a['cls'] == 'scalar']
    pre = [f"  {a['type']} {a['name']} = S.{'i' if a['type'] == 'int' else 'f'}({i});" for i, a in scal]
    def fwdargs():
        out = []
        for i, a in enumerate(A):
            if a['cls'] == 'scalar': out.append(a['name'])
            else: out.append(f"({'const ' if a['const'] else ''}{a['type']} *)S.p({i})")
        return out
    F = k['F']
    fidx = {a['name']: i for i, a in enumerate(A)}
    o.append(f'static int hk_{name}(Slots &S, int mode, Deriv &D) {{')
    o += pre
    o.append(f"  const int W = {k['count']}; D.W = W; D.nf = {len(F)};")
    for j, f in enumerate(F):
        o.append(f"  D.rows[{j}] = {f['rows']}; D.written[{j}] = {int(f['written'])}; D.slot[{j}] = {fidx[f['name']]}; D.fname[{j}] = \"{f['name']}\";")
    o.append(f"  D.tl_ws = (size_t)({k['tl_ws']});")
    o.append(f"  {{ const long long nt_cap = 0; D.ad_ws0 = (size_t)({k['ad_ws']}); }} D.ad_ws_per_cap = (size_t)32 * (size_t)W;")
    o.append('  if (mode == 0) return 0;')
    o.append('  for (unsigned b = 0; b < S.gx; ++b) for (unsigned t = 0; t < S.bx; ++t) {')
    o.append('    blockIdx.x = b; threadIdx.x = t; blockDim.x = S.bx; gridDim.x = S.gx;')
    fa = ', '.join(fwdargs())
    o.append(f'    if (mode == 1) {name}({fa});')
    tl = ', '.join(fwdargs() + [f'D.tin[{j}]' for j in range(len(F))] + [f'D.tout[{j}]' for j, f in enumerate(F) if f['written']] + ['D.ws', 'D.fail'])
    o.append(f'    else if (mode == 2) {name}__tl({tl});')
    ad = ', '.join(fwdargs() + [f'D.bin[{j}]' for j, f in enumerate(F) if f['written']] + [f'D.acc[{j}]' for j in range(len(F))] + ['D.cap', 'D.ws', 'D.fail'])
    o.append(f'    else if (mode == 3) {name}__ad({ad});')
    o.append('  }')
    o.append('  return 0;\n}')
    tab.append(f'  {{"{name}", hk_{name}}},')
o.append('static const struct { const char *name; int (*fn)(Slots &, int, Deriv &); } HK[] = {')
o += tab
o.append('};')
open(sys.argv[2], 'w', newline='\n').write('\n'.join(o) + '\n')
print('host dispatch', len(tab))
