"""Build-time generator (never in a step loop): exact executed-branch tangent and adjoint of the RRTMG-SW gas-optics
launch rsw_taumol_b (hexcore/mpasphys/rrtmg_sw_v842.py:1712), generated by type substitution from the pinned captured
forward source (sha256 3c499c7b...).

The band body rsw_taumol_body and its helpers (RswSpec, rsw_spec, rsw_acc8, rsw_acc4, rsw_selffor, rsw_forr) are copied
unchanged except for three textual substitutions:
  1. `const real*` -> `const float*`        (the k-coefficient table pointers: constants, never differentiated);
  2. in rsw_taumol_body's parameter list, the 14 active per-layer inputs `const float* __restrict__ X` -> `IN X`;
  3. in rsw_taumol_body's parameter list, `real* taug, real* taur` -> `OUT taug, OUT taur`.
Two namespaces instantiate the copy:
  p7swtl: real = adf (value float with the forward's own rounding helpers, tangent double), IN = TlIn (value, tangent)
  p7swad: real = tv  (value float, per-thread tape; reverse sweep = adjoint), IN = AdIn (tape leaf per read)
  p7swac: real = tvc (the same tape, compact: op code and float operands; ad/last-rad), IN = AdInC
The value part of every operation calls the forward's own helpers (rsw_rn_add/sub/mul, mpas_sw_div), so the augmented
primal is the forward bit for bit. The forward source text is emitted first, untouched."""
import hashlib, re, sys
from pathlib import Path

PIN = "3c499c7ba10221067f80e300b1003e382a66245027ae997f254005f80b74e700"
ACTIVE = ["colh2o", "colco2", "colch4", "colo2", "colo3", "colmol", "fac00", "fac01", "fac10", "fac11",
          "selffac", "selffrac", "forfac", "forfrac"]
src_path, out_path = Path(sys.argv[1]), Path(sys.argv[2])
raw = src_path.read_bytes()
if hashlib.sha256(raw).hexdigest() != PIN:
    raise SystemExit("captured SW source hash differs from the pin")
src = raw.decode()


def braced(start):
    i = src.index("{", start); d = 0; j = i
    while True:
        c = src[j]
        if c == "{": d += 1
        elif c == "}":
            d -= 1
            if d == 0: return j + 1
        j += 1


def function(name):
    ms = list(re.finditer(r"__device__[^;{()]*?\b" + name + r"\s*\(", src))
    if len(ms) != 1: raise SystemExit(f"{name}: {len(ms)} definitions")
    return src[ms[0].start():braced(ms[0].end())]


def struct(name):
    m = re.search(r"struct " + name + r"\s*\{", src)
    end = braced(m.start()); end = src.index(";", end) + 1
    return src[m.start():end]


parts = [struct("RswSpec")]
for h in ["rsw_spec", "rsw_acc8", "rsw_acc4", "rsw_selffor", "rsw_forr"]:
    parts.append(function(h))
body = function("rsw_taumol_body")
sig_end = body.index("{")
sig, rest = body[:sig_end], body[sig_end:]
for x in ACTIVE:
    sig, n = re.subn(r"const real\* __restrict__ %s\b" % x, "IN " + x, sig)
    if n != 1: raise SystemExit(f"rsw_taumol_body: active input {x} found {n} times in the parameter list")
sig, n = re.subn(r"real\* taug, real\* taur", "OUT taug, OUT taur", sig)
if n != 1: raise SystemExit("rsw_taumol_body: output parameters not found")
parts.append(sig + rest)
text = "\n\n".join(parts)
text = text.replace("const real*", "const float*")
if re.search(r"\breal\s*\*", text): raise SystemExit("a non-table real pointer is left in the copied text")

here = Path(__file__).parent
support = (here / "rsw_taumol_ad_support.cuh").read_text()
kernels = (here / "rsw_taumol_ad_kernels.cuh").read_text()
NS = {"p7swtl": ("adf", "TlIn", "TlOut"), "p7swad": ("tv", "AdIn", "AdOut"),
      # ad/last-rad: the compact-tape adjoint (rsw_taumol_ad_support.cuh tvc), run by the entry rsw_taumol_b__ad
      "p7swac": ("tvc", "AdInC", "AdOutC")}
ns = []
for name, (real, rin, rout) in NS.items():
    # typedefs inside the namespace, not a using-directive: the source's own global `typedef float real` would make
    # an imported `real` ambiguous
    ns.append("namespace %s {\ntypedef %s real; typedef %s IN; typedef %s OUT;\n%s\n} // namespace %s\n"
              % (name, real, rin, rout, text, name))
out = (src + "\n// ===== generated by gen_rsw_taumol.py from the pinned source above =====\n"
       + support + "\n" + "\n".join(ns) + "\n" + kernels)
out_path.write_text(out)
print("wrote", out_path, len(out), "bytes; copied text sha256", hashlib.sha256(text.encode()).hexdigest()[:8])
