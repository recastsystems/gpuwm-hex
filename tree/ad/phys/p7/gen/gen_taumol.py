"""Build-time generator (never in a step loop): exact executed-branch tangent and
adjoint of the RRTMG-LW gas-optics launch rlw_taumol_batched, generated by type
substitution from the pinned captured forward source (sha256 683d7a07...).

The 16 band bodies and their helpers are copied unchanged except that scalar
`float` becomes the namespace's `real`; three namespaces instantiate them:
  p7fwd: real = float  (transform self-check: must equal the forward bitwise)
  p7tl : real = adf    (value float with identical rounding, tangent double)
  p7ad : real = tv     (value float, per-thread tape; reverse sweep = adjoint)
The forward source text is emitted first, untouched, so the original kernels
stay in the translation unit."""
import hashlib, re, sys
from pathlib import Path

PIN = "683d7a070b22b0586a646f9e1542ce73c396a801767cd92046f4749183efd606"
src_path, out_path = Path(sys.argv[1]), Path(sys.argv[2])
raw = src_path.read_bytes()
if hashlib.sha256(raw).hexdigest() != PIN:
    raise SystemExit("captured LW source hash differs from the pin")
src = raw.decode()

def braced(start):
    i = src.index("{", start); d = 0; j = i
    while True:
        c = src[j]
        if c == "{": d += 1
        elif c == "}":
            d -= 1
            if d == 0: return j + 1
        j += 1

def function(name):
    m = re.search(r"__device__[^;{()]*?\b" + name + r"\s*\(", src)
    if not m: raise SystemExit("missing " + name)
    return src[m.start():braced(m.end())]

def struct(name):
    m = re.search(r"struct " + name + r"\s*\{", src)
    end = braced(m.start()); end = src.index(";", end) + 1
    return src[m.start():end]

def macro(name):
    m = re.search(r"#define " + name + r"\b(?:[^\n]*\\\n)*[^\n]*", src)
    if not m: raise SystemExit("missing macro " + name)
    return m.group(0)

STRUCTS = ["RlwSpecB35", "RlwFacB35", "RlwSpecFac0609"]
HELPERS = ["rlw_pow4", "rlw_b35_spec", "rlw_b35_facs", "rlw_b35_major", "rlw_b35_bmajor",
           "rlw_specfac_0609", "rlw_ninemajor_0609", "rlw_nine_major_b1316"]
TABLE_MACROS = ["CHI35", "RLW1316_A3", "KA9X19", "KA3_0609", "KB5X19"]
BAND_SIG = ("(int ncol, int nl, int col, int lay, int gpoint, int laytrop,\n"
            "    const int* __restrict__ isv, const float* __restrict__ chi_mls, float oneminus,\n"
            "    const float* const* __restrict__ tabs, Ctx& ctx)")

def to_real(text):
    return re.sub(r"\bfloat\b(?!\s*\*)", "real", text)

parts = []
for s in STRUCTS: parts.append(to_real(struct(s)))
for h in HELPERS: parts.append(to_real(function(h)))
for b in range(1, 17):
    f = function(f"rlw_gband{b}")
    m = re.search(r"rlw_gband%d\s*\(" % b, f)
    # replace the parameter list (balanced parentheses) with the context signature
    i = m.end() - 1; d = 0; j = i
    while True:
        if f[j] == "(": d += 1
        elif f[j] == ")":
            d -= 1
            if d == 0: break
        j += 1
    f = f[:i] + BAND_SIG + f[j + 1:]
    f = f.replace("TAUGB_GPOINT_PROLOGUE", "")
    f = f.replace("__forceinline__ ", "")
    parts.append(to_real(f))
body = "\n\n".join(parts)
macros = "\n".join(f"#undef {n}\n{macro(n)}" for n in TABLE_MACROS)

support = Path(__file__).with_name("taumol_ad_support.cuh").read_text()
kernels = Path(__file__).with_name("taumol_ad_kernels.cuh").read_text()
ns = []
for name in ("p7fwd", "p7tl", "p7ad", "p7ac"):   # p7ac: the compact-tape adjoint (ad/last-rad)
    ns.append(f"namespace {name} {{\nusing namespace p7base_{name};\n{body}\n}} // namespace {name}\n")
out = (src + "\n// ===== generated by gen_taumol.py from the pinned source above =====\n"
       + macros + "\n" + support + "\n" + "\n".join(ns) + "\n" + kernels)
out_path.write_text(out)
print("wrote", out_path, len(out), "bytes; helpers", len(HELPERS), "bands 16")
