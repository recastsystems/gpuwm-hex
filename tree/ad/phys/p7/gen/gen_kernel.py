"""Build-time generator (never in a step loop): exact executed-branch tangent and
adjoint of one whole CUDA launch, by type substitution of its pinned source.

Spec (JSON): {"kernel": NAME, "source_sha256": PIN, "active_in": [...],
              "active_out": [...], "tape": N, "writes": M}
The kernel body is copied unchanged except: scalar `float` -> `real`, local
float pointer declarations -> `auto`, and the active float pointer parameters
become array views. Three namespaces instantiate it:
  g7fwd: real = float, views = raw pointers (self-check: must equal the forward)
  g7tl : real = adf, views carry float64 tangents (augmented forward)
  g7ad : real = gtv, a per-thread tape in global scratch; reverse sweep per thread
Refused (no silent fallback): __shared__, __syncthreads, atomics, warp shuffles
in the body."""
import hashlib, json, re, sys
from pathlib import Path

src_path, spec_path, out_path = map(Path, sys.argv[1:4])
spec = json.loads(spec_path.read_text())
raw = src_path.read_bytes()
if hashlib.sha256(raw).hexdigest() != spec["source_sha256"]:
    raise SystemExit("source hash differs from the pin")
src = raw.decode()
K = spec["kernel"]

m = re.search(r'extern "C" __global__ void ' + K + r"\s*\(", src)
if not m: raise SystemExit("kernel not found")
i = m.end() - 1; d = 0; j = i
while True:
    if src[j] == "(": d += 1
    elif src[j] == ")":
        d -= 1
        if d == 0: break
    j += 1
params_text = src[i + 1:j]
b0 = src.index("{", j); d = 0; k = b0
while True:
    if src[k] == "{": d += 1
    elif src[k] == "}":
        d -= 1
        if d == 0: break
    k += 1
body = src[b0:k + 1]
for bad in ("__shared__", "__syncthreads", "atomic", "__shfl"):
    if bad in body: raise SystemExit(f"refused: {bad} in {K} body")

params = []
for p in re.sub(r"//[^\n]*", "", params_text).split(","):
    p = " ".join(p.split())
    name = re.findall(r"(\w+)\s*$", p)[0]
    params.append((p, name))
names = [n for _, n in params]
ain, aout = spec["active_in"], spec["active_out"]
for n in ain + aout:
    if n not in names: raise SystemExit("unknown active parameter " + n)
arrays = ain + aout  # leaf / cotangent ids

def sig(ns):
    out = []
    for p, n in params:
        if n in ain: out.append(f"AIn {n}")
        elif n in aout: out.append(f"AOut {n}")
        else: out.append(p)
    return ", ".join(out)

b = re.sub(r"\bfloat\b(?!\s*\*)", "real", body)
b = re.sub(r"(?:const\s+)?float\s*\*\s*(?:const\s+)?(?:__restrict__\s+)?(\w+)\s*=", r"auto \1 =", b)
fn = f"__device__ void {K}_body({sig(None)})\n{b}\n"

support = Path(__file__).with_name("generic_ad_support.cuh").read_text()
nsdefs = []
for ns in ("g7fwd", "g7tl", "g7ad"):
    nsdefs.append(f"namespace {ns} {{\nusing namespace g7base_{ns};\n{fn}}} // namespace {ns}\n")

call_args = ", ".join(names)
plain_params = ", ".join(p for p, _ in params)
def dparams(prefix, const_in):
    return "".join(f", {'const ' if (const_in and n in ain) else ''}double* __restrict__ {prefix}{n}" for n in arrays)
tl_views = "; ".join(
    [f"g7tl::AIn {n}_v{{{n}, d_{n}}}" for n in ain] + [f"g7tl::AOut {n}_v{{{n}, d_{n}}}" for n in aout])
tl_call = ", ".join(f"{n}_v" if n in arrays else n for n in names)
ad_views = "; ".join(
    [f"g7ad::AIn {n}_v{{{n}, {idx}, &tape}}" for idx, n in enumerate(ain)] +
    [f"g7ad::AOut {n}_v{{{n}, {len(ain) + idx}, &tape}}" for idx, n in enumerate(aout)])
nout = len(aout)
kernels = f"""
// ---- entries for {K} (generated by gen_kernel.py; Apache-2.0) ----
extern "C" __global__ void g7_{K}_fwd({plain_params}) {{
    g7fwd::{K}_body({call_args});
}}
extern "C" __global__ void {K}__tl({plain_params}{dparams('d_', True)}) {{
    {tl_views};
    g7tl::{K}_body({tl_call});
}}
// Adjoint: launch with the forward's geometry on the PRE-launch state. Adds into
// input cotangents; consumes (zeroes) the cotangent of every output word written.
extern "C" __global__ void {K}__ad({plain_params}{dparams('b_', False)},
    G7Scratch* __restrict__ scratch, int* __restrict__ status) {{
    long long tid = ((long long)blockIdx.y * gridDim.x + blockIdx.x) * blockDim.x + threadIdx.x;
    G7Tape tape; tape.init(scratch, tid);
    double* bp[{len(arrays)}] = {{{", ".join("b_" + n for n in arrays)}}};
    {ad_views};
    g7ad::{K}_body({", ".join(f"{n}_v" if n in arrays else n for n in names)});
    tape.finish(bp, {len(ain)}, status);
}}
"""
out = (src + "\n// ===== generated by gen_kernel.py from the pinned source above =====\n"
       + support + "\n" + "\n".join(nsdefs) + kernels)
out_path.write_text(out)
print(json.dumps({"kernel": K, "active_in": ain, "active_out": aout, "bytes": len(out)}))
