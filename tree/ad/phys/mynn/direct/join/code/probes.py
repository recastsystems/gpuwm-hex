def fields():
    out = []
    for p, d in P.items():
        for v in d['prof']: out.append((p, v, 'prof'))
        for v in d['scal']: out.append((p, v, 'scal'))
    return out

def frame_header():
    h = ['#pragma once', '// generated by probes.py: the probed frame of one column (CPU test only)', '#include <cstddef>',
         'namespace jprobe {', 'constexpr int JMAX=62;', 'struct Prof{double v[JMAX];int id[JMAX];double tb[JMAX];};',
         'struct Scal{double v;int id;double tb;};', 'enum Point{' + ','.join(P) + ',NPOINT};',
         'struct Frame{', ' long pos[NPOINT]; int seen[NPOINT];']
    for p, v, kind in fields(): h.append(f' {"Prof" if kind=="prof" else "Scal"} {p}__{v};')
    for v in PROD: h.append(f' Prof T_prod__{v};')
    for v in PRODS: h.append(f' Scal T_prodk__{v}[JMAX];')
    h += ['};', 'extern Frame F;', '}']
    return '\n'.join(h) + '\n'

def probe_code(p):
    d = P[p]; c = [f'jprobe::F.pos[jprobe::{p}]=jprobe_pos();jprobe::F.seen[jprobe::{p}]++;']
    for v in d['prof']:
        c.append(f'for(int jk=({v}).lo[0];jk<=({v}).hi[0]&&jk<jprobe::JMAX;++jk){{jprobe::F.{p}__{v}.v[jk]=jv({v}(jk));jprobe::F.{p}__{v}.id[jk]=jd({v}(jk));}}')
    for v in d['scal']:
        c.append(f'jprobe::F.{p}__{v}.v=jv({v});jprobe::F.{p}__{v}.id=jd({v});')
    return '\n'.join(c) + '\n'

def func_span(u, name):
    m = re.search(r'\n[^\n]*\b' + name + r'\([^\n]*\) \{', u)
    assert m, name
    a = m.start() + 1; b = m.end(); depth = 1
    while depth: depth += (u[b] == '{') - (u[b] == '}'); b += 1
    return a, m.end(), b

def insert(u):
    # process later insertions first inside each function to keep offsets valid: collect (pos, text)
    edits = []
    for p, d in P.items():
        a, bodystart, b = func_span(u, d['scope'])
        if d['where'] == 'after-sig':
            edits.append((bodystart, '\n' + probe_code(p))); continue
        body = u[a:b]; i = -1
        for _ in range(d['occ'] + 1):
            i = body.index(d['anchor'], i + 1)
        pos = a + i
        if d['where'] == 'after':
            pos = u.index(';\n', pos) + 2
        edits.append((pos, probe_code(p)))
    # production level capture, before elq inside f_mym_turbulence
    a, _, b = func_span(u, T); i = u.index('elq = r6_mul(el(k), qkw(k));', a); assert i < b
    code = ''.join(f'jprobe::F.T_prod__{v}.v[k]=jv({v}(k));' for v in PROD) + \
           ''.join(f'jprobe::F.T_prodk__{v}[k].v=jv({v});' for v in PRODS) + '\n'
    edits.append((i, code))
    for pos, text in sorted(edits, key=lambda e: -e[0]):
        u = u[:pos] + text + u[pos:]
    return u

