"""Probe spec and insertion for the whole-column oracle (CPU test only).
Inserts value/node-id captures at named program points of the frozen native column
(repository scalar tape rules, float primals). Changes no arithmetic: probes only read.
Each point also records the tape position, so a partial reverse sweep to that position
gives the exact after-cut bar of every probed value (the whole-column oracle)."""
